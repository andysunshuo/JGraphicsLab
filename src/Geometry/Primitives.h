// ============================================================
// 一、基础数据结构
// ============================================================

// 二维几何点
//
// 表示二维平面中的一个位置。
//
// 例如：
// Point2 p = {20.0f, 30.0f};
//
// p.x 表示 X 坐标
// p.y 表示 Y 坐标
//
// 注意：
// Point2 使用 float，因为几何位置可能存在小数。
// 真正调用 PutPixel 时，需要转换为整数像素坐标。
struct Point2
{
    float x;
    float y;
};

// 二维三角形
//
// a、b、c 分别表示三个顶点。
//
// 三个顶点共同确定一个三角形。
//
// 例如：
// Triangle t = {
//     {10.0f, 10.0f},
//     {80.0f, 20.0f},
//     {40.0f, 90.0f}
// };
struct Triangle
{
    Point2 a;
    Point2 b;
    Point2 c;
};

// 重心坐标
//
// alpha：顶点 A 的权重
// beta ：顶点 B 的权重
// gamma：顶点 C 的权重
//
// 满足：
// alpha + beta + gamma = 1
//
// HW10 用来计算。
// HW11 使用它进行颜色插值。
struct Barycentric
{
    float alpha;
    float beta;
    float gamma;
};
